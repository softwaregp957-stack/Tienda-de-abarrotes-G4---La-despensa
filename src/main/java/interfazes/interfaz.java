    private void CargarPanelInicio(ProductoDao pDAO, VentaDao vDAO) {
    String hoy = java.time.LocalDate.now().toString(); // "yyyy-MM-dd"

    int ventasHoy = 0;
    int totalHoy = 0;
    for (Venta v : vDAO.listarVentas()) {
        if (v.getFecha() != null && v.getFecha().startsWith(hoy)) {
            ventasHoy++;
            totalHoy += v.getTotal();
        }
    }
    lblVentasHoyValor.setText(String.valueOf(ventasHoy));
    lblTotalHoyValor.setText(String.valueOf(totalHoy));

    List<Producto> productos = pDAO.listarTodos();
    lblProductosValor.setText(String.valueOf(productos.size()));

    // Tabla de productos con stock bajo (ajusta el umbral a tu gusto)
    int umbralStockBajo = 5;
    List<Producto> stockBajo = new ArrayList<>();
    for (Producto p : productos) {
        if (p.getStock() <= umbralStockBajo) {
            stockBajo.add(p);
        }
    }
    Object[][] filas = new Object[stockBajo.size()][3];
    for (int i = 0; i < stockBajo.size(); i++) {
        Producto p = stockBajo.get(i);
        filas[i][0] = p.getId_producto();
        filas[i][1] = p.getNombre_producto();
        filas[i][2] = p.getStock();
    }
    String[] columnas = {"ID", "Nombre", "Stock"};
    tblStockBajo.setModel(new javax.swing.table.DefaultTableModel(filas, columnas) {
        @Override
        public boolean isCellEditable(int row, int col) {
            return false;
        }
    });
}
    
    

